"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
test("3D Harvest World is a Babylon scene shared with Android", () => {
 const web = fs.readFileSync(path.join(root, "harvest-world-3d.js"), "utf8");
 const android = fs.readFileSync(path.join(root, "android/app/src/main/assets/harvest-world-3d.js"), "utf8");
 const game = fs.readFileSync(path.join(root, "game.js"), "utf8");
 const androidGame = fs.readFileSync(path.join(root, "android/app/src/main/assets/game.js"), "utf8");
 const html = fs.readFileSync(path.join(root, "index.html"), "utf8");
 const androidHtml = fs.readFileSync(path.join(root, "android/app/src/main/assets/index.html"), "utf8");
 assert.equal(android, web, "Android 3D runtime must match browser runtime");
 assert.equal(androidGame, game, "Android game progression must match browser progression");
 assert.equal(androidHtml, html, "Android HTML must match browser HTML");
 for (const feature of ["BABYLON.Engine", "BABYLON.ShadowGenerator", "useBlurExponentialShadowMap=true", "shadowGenerator.addShadowCaster(mesh,true)", "scene.shadowsEnabled=true", "get shadowsEnabled()", "level-gate-", "harvest-progress-tractor", "tractor-road-journey", "tractor-wheel-roll-", "tractorPosition", "tractorVisible", "ArcRotateCamera", "onSelectLevel", "ImportMeshAsync", "harvest-world-farmstead.glb", "harvest-world-terrain.glb", "harvest-world-settlement.glb", "terrainLoaded", "settlementLoaded", "settlementMeshCount", "terrainMeshCount", "farmsteadMeshCount", "gateCount", "settlementAnchors", "cameraPosition", "cameraTarget", "gatePositions", "settlementPositions", "settlementScreenBounds", "getSettlementScreenBounds", "BABYLON.Vector3.Project", "overrideCloneAlphaBetaRadius", "Promise.all"]) {
  assert.ok(web.includes(feature), "3D scene is missing " + feature);
 }
 assert.match(html, /src="\.\/vendor\/babylon\.js"/);
 assert.doesNotMatch(html, /cdn\.babylonjs\.com/);
 assert.match(fs.readFileSync(path.join(root, "scripts/prepare-babylon-runtime.js"), "utf8"), /babylonjs\/babylon\.js/);
 assert.match(html, /harvest-world-canvas/);
 assert.match(game, /HarvestWorld3D\.focusLevel\(level,true\)/);
 assert.ok(html.includes("babylonjs.loaders.min.js"));
 assert.ok(web.includes("harvest-world-farmstead.glb"));
 assert.ok(fs.readFileSync(path.join(root, "scripts/build_harvest_world_assets.py"), "utf8").includes("export_scene.gltf"));
 const terrainBuilder = fs.readFileSync(path.join(root, "scripts/build_harvest_world_terrain.py"), "utf8");
 assert.ok(terrainBuilder.includes("Continuous asphalt road surface"));
 assert.ok(terrainBuilder.includes("Sculpted Zimbabwe countryside terrain"));
 assert.ok(terrainBuilder.includes("terrain_height"));
 assert.ok(terrainBuilder.includes("def apply_surface_variation(obj, surface):"), "terrain must bake natural surface colour variation into GLB vertex colours");
 assert.ok(terrainBuilder.includes('color_attributes.new(name="Color", type="BYTE_COLOR", domain="POINT")'));
 assert.ok(terrainBuilder.includes('apply_surface_variation(terrain, "grass")'));
 assert.ok(terrainBuilder.includes('apply_surface_variation(obj, "asphalt")'));
 assert.ok(terrainBuilder.includes('apply_surface_variation(obj, "shoulder")'));
 assert.ok(terrainBuilder.includes("dry_patch") && terrainBuilder.includes("wear = broad") && terrainBuilder.includes("dust = broad"));
 assert.ok(terrainBuilder.includes("verts.append((x, -z, broad + undulation - .5))"));
 assert.ok(terrainBuilder.includes("MAX_TERRAIN_MESHES = 12"));
 assert.ok(terrainBuilder.includes("Rural timber electricity pole"), "terrain must include rural power poles");
 assert.ok(terrainBuilder.includes("Sagging overhead rural power cable"), "terrain must include overhead power lines");
 assert.ok(terrainBuilder.includes("Weathered rural fence post"), "terrain must include roadside rural fencing");
 assert.ok(terrainBuilder.includes("Rural timber fence rail"), "rural fencing must have rails");
 assert.ok(terrainBuilder.includes("Natural irregular msasa canopy"), "tree canopies must have irregular natural silhouettes");
 assert.ok(terrainBuilder.includes("Zimbabwe roadside scrub cluster"), "roadside landscape must include indigenous scrub clusters");
 assert.ok(terrainBuilder.includes("Break the perfect sphere silhouette into weathered granite shoulders"), "granite kopjes must have weathered non-spherical forms");
 assert.ok(terrainBuilder.includes("MAX_TERRAIN_MESHES = 12"), "natural foliage must remain within the terrain draw-call budget");
 const textureBuilder = fs.readFileSync(path.join(root, "scripts/harvest_world_textures.py"), "utf8");
 assert.ok(textureBuilder.includes("TEXTURE_PROFILES"), "Harvest World must define reusable surface texture profiles");
 assert.ok(textureBuilder.includes("image.pack()"), "surface maps must be packed into GLB files for offline use");
 assert.ok(textureBuilder.includes("bpy.ops.uv.smart_project"), "authored meshes must receive UV coordinates");
 assert.ok(textureBuilder.includes("ShaderNodeNormalMap"), "surface materials must include subtle relief maps");
 assert.ok(textureBuilder.includes('colorspace_settings.name = "Non-Color"'), "normal maps must use non-colour data");
 assert.ok(textureBuilder.includes("shader.inputs[\"Base Color\"].default_value"), "textures must preserve each authored material tint");
 assert.ok(textureBuilder.includes("Applied packed offline Harvest World textures"), "texture generation must report applied material profiles");
 for (const builderPath of ["scripts/build_harvest_world_assets.py", "scripts/build_harvest_world_terrain.py", "scripts/build_harvest_world_settlement.py"]) {
  const builder = fs.readFileSync(path.join(root, builderPath), "utf8");
  assert.ok(builder.includes("from harvest_world_textures import apply_harvest_textures"));
  assert.ok(builder.includes("apply_harvest_textures()"), builderPath + " must texture assets before batching");
 }
 const farmsteadBuilder = fs.readFileSync(path.join(root, "scripts/build_harvest_world_assets.py"), "utf8");
 assert.ok(farmsteadBuilder.includes("MAX_FARMSTEAD_MESHES = 12"));
 assert.ok(farmsteadBuilder.includes("bpy.ops.object.join()"));
 const settlementBuilder = fs.readFileSync(path.join(root, "scripts/build_harvest_world_settlement.py"), "utf8");
 for (const feature of ["Main homestead", "Second dwelling", "Traditional thatched grain-store roof", "Elevated galvanized water tank", "Community borehole", "Homestead fence rail", "Layered msasa orchard canopy", "Ripe orchard fruit", "Poultry coop timber body", "Free-range village hen", "Worn homestead footpath stone"]) assert.ok(settlementBuilder.includes(feature), "settlement model is missing " + feature);
 assert.ok(web.includes("blender-authored-rural-settlement-west"));
 assert.ok(web.includes("blender-authored-rural-settlement-east"));
 assert.ok(web.includes("settlementEastZ=38,settlementEastX=roadX(settlementEastZ)+12.5"));
 assert.ok(web.includes("settlementWestZ=74,settlementWestX=roadX(settlementWestZ)-4.5"));
 assert.ok(web.includes("farmsteadZ=14,farmsteadX=roadX(farmsteadZ)+11.5"));
 assert.ok(web.includes("const target=gate.group.position.add(new BABYLON.Vector3(-4.8,0,0))"), "camera must centre the asphalt lane rather than the roadside gate");
 assert.ok(web.includes("camera.setTarget(target,false,false,true)"));
 assert.ok(web.includes("camera.setPosition(target.add(offset))"));
 assert.ok(web.includes("camera.overrideCloneAlphaBetaRadius=true"));
 assert.ok(web.includes("road-camera-drive-target"));
 assert.ok(web.includes("road-camera-drive-position"));
 assert.ok(web.includes("finishedAnimations===2"));
 assert.ok(web.includes("camera.setPosition(endPosition)"));
 assert.ok(web.includes("ANIMATIONLOOPMODE_CONSTANT,undefined,finish"));
 assert.ok(web.includes("createTractor(new BABYLON.Vector3(firstRoadX,terrainHeight(firstRoadX,firstRoadZ)+.27,firstRoadZ))"));
 assert.ok(web.includes("moveTractor(tractorTarget,animate)"));
 assert.ok(web.includes("tractorWheels.forEach((wheel,index)=>"));
 assert.ok(web.includes("wheel.rotation.z=Math.PI/2"));
 for (const detail of ["exposed brick plinth","brick corner pier","timber window shutter","stone window lintel","stone doorway lintel","raised entrance step","galvanised rain gutter","rainwater downpipe"]) {
  assert.ok(settlementBuilder.includes(detail), "rural house architecture is missing " + detail);
 }
 assert.ok(settlementBuilder.includes("for course in range(3)"), "house facade must have layered masonry courses");
 assert.ok(settlementBuilder.includes("Continuous eaves gutters") || settlementBuilder.includes("eaves gutters"), "houses must include rainwater drainage details");
 assert.match(settlementBuilder, /MAX_SETTLEMENT_MESHES = 12/);
 assert.ok(settlementBuilder.includes("bpy.ops.object.join()"), "settlement geometry must be batched by material");
 assert.ok(settlementBuilder.includes("material-batched meshes"));
 assert.ok(!web.includes("buildHouse("), "procedural roadside houses must be replaced by the authored settlement model");
 assert.doesNotMatch(web, /river-valley/);
 const browserWorkflow = fs.readFileSync(path.join(root, ".github/workflows/android-layout-smoke.yml"), "utf8");
 assert.equal((browserWorkflow.match(/blender --background --python scripts\/build_harvest_world_terrain.py/g) || []).length, 2, "both Android build and browser QA jobs must generate the terrain GLB");
 assert.equal((browserWorkflow.match(/test_harvest_world_glb.py/g) || []).length, 2, "both Android build and browser QA jobs must validate the generated GLBs");
 for (const workflowName of ["android-apk.yml", "android-release-candidate.yml", "android-signed-release.yml", "publish-web-preview.yml"]) {
  const workflow = fs.readFileSync(path.join(root, ".github/workflows", workflowName), "utf8");
  assert.ok(workflow.includes("test_harvest_world_glb.py"), workflowName + " must validate generated GLB geometry");
  assert.ok(workflow.includes("scripts/build_harvest_world_terrain.py"), workflowName + " must generate the 3D terrain");
 }
 assert.ok(fs.readFileSync(path.join(root, ".github/workflows/android-signed-release.yml"), "utf8").includes("babylonjs-loaders@9.36.0"));
 assert.ok(fs.readFileSync(path.join(root, "sw.js"), "utf8").includes("harvest-world-terrain.glb"));
 assert.ok(fs.readFileSync(path.join(root, "sw.js"), "utf8").includes("harvest-world-settlement.glb"));
 assert.equal(fs.readFileSync(path.join(root, "android/app/src/main/assets/sw.js"), "utf8"), fs.readFileSync(path.join(root, "sw.js"), "utf8"));
 assert.match(fs.readFileSync(path.join(root, "scripts/prepare-babylon-runtime.js"), "utf8"), /babylonjs-loaders/);
});
